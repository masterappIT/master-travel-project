#!/usr/bin/env node
// Generates the passenger app's Traditional -> Simplified Chinese table (src/i18n/zh-hans-map.ts) from OpenCC data.
// Run `node scripts/build-zh-hans-map.mjs` after adding passenger text; `--check` fails when the file is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const { Converter } = createRequire(import.meta.url)('opencc-js')
const convert = Converter({ from: 'hk', to: 'cn' })
const root = process.cwd()
const output = path.join(root, 'src/i18n/zh-hans-map.ts')

// Every CJK ideograph whose simplified form differs, converted one character at a time.
let traditional = ''
let simplified = ''
const charMap = new Map()
for (const [start, end] of [[0x3400, 0x4dbf], [0x4e00, 0x9fff]]) {
  for (let code = start; code <= end; code += 1) {
    const char = String.fromCharCode(code)
    const converted = convert(char)
    if (converted === char || converted.length !== 1) continue
    traditional += char
    simplified += converted
    charMap.set(char, converted)
  }
}
const byChar = (text) => Array.from(text, (char) => charMap.get(char) ?? char).join('')

// OpenCC converts some words differently from their separate characters (著名 stays 著名, not 着名).
// Record the wording used in the passenger source where that happens, so the app's own text is exact.
const sourceFiles = []
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) { if (entry.name !== 'static' && entry.name !== 'uni_modules') walk(file) }
    else if (/\.(vue|ts|js|json)$/.test(entry.name) && file !== output) sourceFiles.push(file)
  }
}
walk(path.join(root, 'src'))
const phrases = new Map()
for (const file of sourceFiles) {
  for (const run of readFileSync(file, 'utf8').match(/[㐀-䶿一-鿿]+/g) ?? []) {
    const exact = convert(run)
    if (exact !== byChar(run) && exact.length === run.length) phrases.set(run, exact)
  }
}
const phraseList = [...phrases].sort(([a], [b]) => b.length - a.length || a.localeCompare(b))

const content = `// Generated by scripts/build-zh-hans-map.mjs from OpenCC data. Do not edit by hand.
export const TRADITIONAL_CHARACTERS = '${traditional}'
export const SIMPLIFIED_CHARACTERS = '${simplified}'
export const SIMPLIFIED_PHRASES: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(phraseList)}
`
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) {
    console.error('src/i18n/zh-hans-map.ts is stale. Run `node scripts/build-zh-hans-map.mjs`.')
    process.exit(1)
  }
  console.log('Simplified Chinese table is up to date.')
} else {
  writeFileSync(output, content)
  console.log(`Wrote ${traditional.length} characters and ${phraseList.length} phrases.`)
}
