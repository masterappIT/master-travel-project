#!/usr/bin/env python3
"""Split the Driver Web CJK fonts into UI / common / rare layers.

Only the UI layer is in the Flutter FontManifest (loaded before the first
frame). The common and rare layers are loaded on demand by
lib/core/fonts/driver_font_layers.dart before any text that needs them is
shown, so no character renders as a missing-glyph box.

Every layer is cut from the committed source fonts, so glyph outlines and the
variable weight axis are unchanged:
  - assets/fonts/NotoSansTC-Variable.ttf
  - assets/fonts/NotoSansSC-Supplement.ttf (code points missing from TC)

Layers:
  UI     every character in lib/**/*.dart plus ASCII and common punctuation
  common GB2312 and Big5 level-1 characters not in UI
  rare   everything else covered by the source fonts

Usage (fontTools==4.66.0), from driver/:
  python3 tool/build_driver_font_layers.py
"""
import glob
import hashlib
import os

import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

EXPECTED_FONTTOOLS = "4.66.0"
SOURCES = {
    "TC": ("assets/fonts/NotoSansTC-Variable.ttf",
           "864727d210d54f2537bbe23b3a839436c3992af72de9322af5270897246bd44f"),
    "SC": ("assets/fonts/NotoSansSC-Supplement.ttf",
           "a544e0db477ffd75061a6ea01ccfc963a0f96b198637d101aa379a6d14e7a554"),
}
LAYERS = ("UI", "Common", "Rare")
COVERAGE_DART = "lib/core/fonts/driver_font_coverage.g.dart"


def sha256(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def ui_code_points():
    points = set(range(0x20, 0x7F))
    for start, end in ((0xA0, 0x100), (0x2000, 0x2070), (0x2190, 0x2200),
                       (0x3000, 0x3040), (0xFF00, 0xFFF0)):
        points.update(range(start, end))
    for path in glob.glob("lib/**/*.dart", recursive=True):
        if path.endswith(".g.dart"):
            continue
        with open(path, encoding="utf-8") as handle:
            points.update(ord(char) for char in handle.read())
    return points


def common_code_points():
    points = set()
    for high in range(0xB0, 0xF8):  # GB2312 hanzi
        for low in range(0xA1, 0xFF):
            try:
                points.add(ord(bytes([high, low]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    for high in range(0xA4, 0xC7):  # Big5 level-1 hanzi
        for low in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
            try:
                points.add(ord(bytes([high, low]).decode("big5")))
            except UnicodeDecodeError:
                pass
    return points


def ranges(points):
    result = []
    for point in sorted(points):
        if result and result[-1][1] == point - 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def write_subset(source, points, out):
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.glyph_names = False
    font = subset.load_font(source, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(points))
    subsetter.subset(font)
    subset.save_font(font, out, options)


def main():
    if fontTools.version != EXPECTED_FONTTOOLS:
        raise SystemExit(f"fontTools {EXPECTED_FONTTOOLS} required, found {fontTools.version}")
    for path, digest in SOURCES.values():
        if sha256(path) != digest:
            raise SystemExit(f"Unexpected source font {path}")

    ui = ui_code_points()
    common = common_code_points() - ui
    layer_points = {"UI": ui, "Common": common}
    deferred = {"Common": set(), "Rare": set()}
    for script, (path, _) in SOURCES.items():
        covered = set(TTFont(path).getBestCmap())
        split = {
            "UI": covered & ui,
            "Common": covered & common,
            "Rare": covered - ui - common,
        }
        for layer in LAYERS:
            out = f"assets/fonts/NotoSans{script}-{layer}.ttf"
            write_subset(path, split[layer], out)
            if layer != "UI":
                deferred[layer] |= split[layer]
            print(f"{out}: {len(split[layer])} code points, sha256 {sha256(out)}")

    lines = [
        "// GENERATED by tool/build_driver_font_layers.py. Do not edit.",
        "// Delta-encoded code point runs per deferred font layer: pairs of",
        "// (gap from the previous run's end, run length).",
        "",
    ]
    for layer in ("Common", "Rare"):
        deltas, previous = [], 0
        for start, end in ranges(deferred[layer]):
            deltas += [start - previous, end - start + 1]
            previous = end + 1
        flat = ",".join(str(value) for value in deltas)
        lines.append(f"const driverFont{layer}Ranges = <int>[{flat}];")
    os.makedirs(os.path.dirname(COVERAGE_DART), exist_ok=True)
    with open(COVERAGE_DART, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"{COVERAGE_DART}: common {len(ranges(deferred['Common']))} ranges, "
          f"rare {len(ranges(deferred['Rare']))} ranges")


if __name__ == "__main__":
    main()
